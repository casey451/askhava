"""Generate twin/oracle/license_scope.json, the Twin gate's license oracle, from the catalog (D-107, D-541).

The oracle says which job types each license may receive. It is read only from
docs/catalog/categories.yaml and docs/catalog/license_map.yaml (LIC-001, LIC-043, CARD-001), never
from twin/app.py or app/ (docs/twin-warnings.md section 2, 6.3 item 4), and is checked against
docs/catalog/matching_examples.yaml by the gate's self-test (D-110). The file holds:

- `grants`: every license map row (ROC class, agency, city list) -> {category: [job types]}, with
  `includes` followed and the city list granting every job type of a no-license category;
- `twin`: every twin license class -> the twin job types it covers, through the crosswalk under
  "catalog" in twin/twin_config.json (a '*' pair needs every job type of its category);
- `sources`: the sha256 of the two catalog files and of the crosswalk (canonical JSON), so a catalog edit shows in the diff.

Run `python3 twin/oracle/gen_license_scope.py` after any catalog change; `--check` exits 1 if the
committed file differs from a fresh generation (no hand edits); the gate makes the same comparison
through `generate(root)` and `render` before every run. Tooling: PyYAML, safe_load only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml  # type: ignore[import-untyped]  # reason: PyYAML ships no stubs; only safe_load is used

ROOT = Path(__file__).resolve().parents[2]
CATEGORIES = Path("docs") / "catalog" / "categories.yaml"
LICENSE_MAP = Path("docs") / "catalog" / "license_map.yaml"
TWIN_CONFIG = Path("twin") / "twin_config.json"
OUT = Path("twin") / "oracle" / "license_scope.json"


def sha256(data: bytes) -> str:
    """An input's fingerprint, recorded in the oracle so a catalog edit shows in its diff (D-541)."""
    return hashlib.sha256(data).hexdigest()


def direct_grants(row: dict, cats: dict[str, dict]) -> dict[str, set[str]]:
    """LIC-043: one row's own grants: `all` (the category's job types) or `only`, plus `also` and the
    record-category jobs an agency covers (LIC-012, D-504); the city list covers no-license categories."""
    out: dict[str, set[str]] = {}
    for cat_id, grant in (row.get("job_types") or {}).items():
        base = cats[cat_id]["job_types"] if grant.get("all") else grant.get("only", [])
        out[cat_id] = {str(j) for j in [*base, *grant.get("also", []), *(row.get("record_category_needed") or {})]}
    if row.get("no_license_categories"):
        for cat_id, cat in cats.items():
            if cat["license"]["kind"] == "none":
                out.setdefault(cat_id, set()).update(str(j) for j in cat["job_types"])
    return out


def row_grants(name: str, rows: dict[str, dict], cats: dict[str, dict], seen: frozenset[str]) -> dict[str, set[str]]:
    """LIC-043: a row's grants with every class it `includes` (a dual or KB class), once each."""
    out = direct_grants(rows[name], cats)
    for inc in rows[name].get("includes", []):
        if inc not in seen:
            for cat_id, jobs in row_grants(inc, rows, cats, seen | {inc}).items():
                out.setdefault(cat_id, set()).update(jobs)
    return out


def twin_covers(grants: dict[str, set[str]], pairs: list[list[str]], cats: dict[str, dict]) -> bool:
    """CARD-001: a license covers a twin job type when it covers every catalog job type it stands for."""
    need = [(c, j) for c, job in pairs for j in (cats[c]["job_types"] if job == "*" else [job])]
    return all(j in grants.get(c, set()) for c, j in need)


def generate(root: Path = ROOT) -> dict:
    """The oracle, built from the catalog and the twin's crosswalk under `root` alone (the gate passes its own root)."""
    cats = {c["id"]: c for c in yaml.safe_load((root / CATEGORIES).read_text(encoding="utf-8"))["categories"]}
    lmap = yaml.safe_load((root / LICENSE_MAP).read_text(encoding="utf-8"))
    rows = {str(r["class"]): r for r in lmap["classes"]} | {str(r["license"]): r for r in lmap["agencies"]}
    grants = {name: row_grants(name, rows, cats, frozenset({name})) for name in sorted(rows)}
    cross = json.loads((root / TWIN_CONFIG).read_text(encoding="utf-8"))["catalog"]
    twin = {}
    for cls, names in sorted(cross["license_classes"].items()):
        held: dict[str, set[str]] = {}
        for name in names:
            for cat_id, jobs in grants[name].items():
                held.setdefault(cat_id, set()).update(jobs)
        twin[cls] = sorted(jt for jt, pairs in cross["job_types"].items() if twin_covers(held, pairs, cats))
    return {
        "_about": "Generated by twin/oracle/gen_license_scope.py from the catalog (D-541). Do not edit by hand.",
        "sources": {
            **{p.as_posix(): sha256((root / p).read_bytes()) for p in (CATEGORIES, LICENSE_MAP)},
            "twin/twin_config.json#catalog": sha256(json.dumps(cross, sort_keys=True).encode()),
        },
        "twin": twin,
        "grants": {n: {c: sorted(j) for c, j in sorted(g.items())} for n, g in grants.items()},
    }


def render(data: dict) -> str:
    """One line per license row, so a catalog change shows as a readable diff."""
    lines = ["{"]
    keys = list(data)
    for i, key in enumerate(keys):
        tail = "," if i < len(keys) - 1 else ""
        if isinstance(data[key], dict):
            inner = [f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in data[key].items()]
            lines.append(f" {json.dumps(key)}: {{\n" + ",\n".join(inner) + f"\n }}{tail}")
        else:
            lines.append(f" {json.dumps(key)}: {json.dumps(data[key])}{tail}")
    return "\n".join(lines) + "\n}\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Twin gate's license oracle (D-541)")
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed file is not a fresh generation")
    args = parser.parse_args(argv)
    text = render(generate())
    if args.check:
        same = (ROOT / OUT).is_file() and (ROOT / OUT).read_text(encoding="utf-8") == text
        print("license_scope.json is " + ("current" if same else "stale or hand-edited: regenerate it"))
        return 0 if same else 1
    (ROOT / OUT).write_text(text, encoding="utf-8")
    print(f"wrote {OUT.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
